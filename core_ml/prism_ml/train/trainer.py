import os
import pickle # <-- NEW: Built-in library to save Python objects
import polars as pl
from flaml import AutoML
from typing import Dict, Any
from prism_ml.exceptions import TrainingConfigurationError
import joblib
import os
import uuid
import pandas as pd

class PrismTrainer:
    def __init__(self):
        print("🧠 Prism AutoML Trainer Initialized")

   

   

    def _safe_pandas_conversion(self, df: pl.DataFrame, target_col: str):
        """
        Helper Method: Safely converts Polars to Pandas at high speed.
        Sanitizes column headers and uses vectorized C-level casting for data.
        """
        print("🔄 Executing High-Speed Polars-to-Pandas Translation...")
        
        # 1. Native Conversion
        pdf = df.to_pandas()
        
        # ---------------------------------------------------------
        # THE HOLY GRAIL FIX: Sanitize the column headers!
        # This stops the 'StringDtype' crash inside FLAML's index checker.
        # ---------------------------------------------------------
        pdf.columns = pdf.columns.astype('object') 
        
        # 2. HIGH-SPEED VECTORIZED ARMOR FOR THE DATA (No .to_list() loops!)
        for col in pdf.columns:
            # Catch all variations of strings, objects, and PyArrow types
            if pd.api.types.is_string_dtype(pdf[col]) or pd.api.types.is_object_dtype(pdf[col]):
                if col != target_col:
                    # Instantly cast entire feature column to Category via C-backend
                    pdf[col] = pdf[col].astype('category')
                else:
                    # Target column must be standard Python strings/objects for classification
                    pdf[col] = pdf[col].astype(str).astype('object')
                    
        return pdf
    # Notice we added raw_data_path here!
    def execute_training(self, node_id: str, df: pl.DataFrame, parameters: Dict[str, Any], raw_data_path: str):
        """
        Executes the AutoML training instructions generated by the AI Router.
        """
        # 1. Extract the Target Column
        target_col = parameters.get("target_column")
        if not target_col:
            raise TrainingConfigurationError(
                node_id=node_id, 
                message="No target column specified. The AI cannot train without knowing what to predict."
            )
            
        if target_col not in df.columns:
            raise TrainingConfigurationError(
                node_id=node_id,
                message=f"Target column '{target_col}' not found in the dataset."
            )

        # 2. Extract Training Parameters
        time_budget = parameters.get("time_budget_seconds", 10) 
        estimator_list = parameters.get("model_family", ["xgboost", "rf", "lgbm"])
        if isinstance(estimator_list, str):
            estimator_list = [estimator_list]

        print(f"🚀 Starting FLAML AutoML. Target: '{target_col}' | Budget: {time_budget}s")
        print(f"🤖 Allowed Models: {estimator_list}")

        # 3. Convert Polars to Pandas (FLAML requirement) via our safe helper method
        pdf = self._safe_pandas_conversion(df,target_col)
        
        y = pdf[target_col]
        X = pdf.drop(columns=[target_col])

        # 4. Initialize and Run FLAML
        automl = AutoML()
        automl_settings = {
            "time_budget": time_budget,
            "metric": 'auto',
            "estimator_list": estimator_list,
            "task": 'regression' if y.dtype in ['float64', 'int64'] else 'classification',
            "log_file_name": 'prism_training.log',
            "verbose": 0 
        }
        # ==========================================
        # AI TRANSLATOR FIX: Catch Hallucinated Model Names
        # ==========================================
        # If Llama 3 tries to force specific models, we need to translate them 
        # to FLAML's strict internal naming, or just let FLAML decide!
        
        # A map of common AI hallucinations to FLAML strict keys
        FLAML_MAP = {
            "random_forest": "rf",
            "randomforest": "rf",
            "xg_boost": "xgboost",
            "lightgbm": "lgbm",
            "gradient_boosting": "lgbm",
            "logistic_regression": "lrl1",
            "linear_regression": "lrl1",
            "svm": "svc",
            "support_vector_machine": "svc"
        }

        if 'estimator_list' in automl_settings:
            raw_list = automl_settings['estimator_list']
            # If it's a string, make it a list
            if isinstance(raw_list, str):
                raw_list = [raw_list]
                
            clean_list = []
            for est in raw_list:
                est_clean = est.lower().strip()
                # Translate it if it's in our map, otherwise assume Llama got it right
                clean_list.append(FLAML_MAP.get(est_clean, est_clean))
            
            # Double check against FLAML's actual allowed list just to be safe
            allowed_flaml = ['xgboost', 'xgb_limitdepth', 'rf', 'lgbm', 'lrl1', 'lrl2', 'catboost', 'extra_tree', 'kneighbor']
            final_list = [e for e in clean_list if e in allowed_flaml]
            
            if final_list:
                automl_settings['estimator_list'] = final_list
            else:
                # If Llama gave us total garbage, delete the restriction and let FLAML test everything!
                del automl_settings['estimator_list']
        # ==========================================

        # Train the model!
        automl.fit(X_train=X, y_train=y, **automl_settings)

        print("\n✅ Training Complete!")
        print(f"🏆 Best Model Found: {automl.best_estimator}")
        print(f"📉 Best Loss: {automl.best_loss}")
        
        # 5. DYNAMIC SAVING (The Magic Fix)
        # This automatically extracts 'backend/app/data/usr_123' from the raw path!
        dataset_directory = os.path.dirname(raw_data_path)
        run_id = uuid.uuid4().hex[:8]
        save_path = os.path.join(dataset_directory, f"trained_model_{run_id}.pkl")        
        joblib.dump(automl, save_path)
        print(f"💾 Model securely saved to disk at: {save_path}")

        return automl,save_path