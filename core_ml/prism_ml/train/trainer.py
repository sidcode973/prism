import os
import pickle # <-- NEW: Built-in library to save Python objects
import polars as pl
from flaml import AutoML
from typing import Dict, Any
from prism_ml.exceptions import TrainingConfigurationError

class PrismTrainer:
    def __init__(self):
        print("🧠 Prism AutoML Trainer Initialized")

    # <-- NEW: Added 'save_dir' as an optional parameter
    def execute_training(self, node_id: str, df: pl.DataFrame, parameters: Dict[str, Any], save_dir: str = None):
        """
        Executes the AutoML training instructions generated by the AI Router.
        """
        # 1. Extract the Target Column
        target_col = parameters.get("target_column")
        if not target_col:
            raise TrainingConfigurationError(
                node_id=node_id, 
                message="No target column specified. The AI cannot train without knowing what to predict."
            )
            
        if target_col not in df.columns:
            raise TrainingConfigurationError(
                node_id=node_id,
                message=f"Target column '{target_col}' not found in the dataset."
            )

        # 2. Extract Training Parameters
        time_budget = parameters.get("time_budget_seconds", 10) 
        estimator_list = parameters.get("model_family", ["xgboost", "rf", "lgbm"])
        if isinstance(estimator_list, str):
            estimator_list = [estimator_list] 

        print(f"🚀 Starting FLAML AutoML. Target: '{target_col}' | Budget: {time_budget}s")
        print(f"🤖 Allowed Models: {estimator_list}")

        # 3. Convert Polars to Pandas
        pdf = df.to_pandas()
        
        y = pdf[target_col]
        X = pdf.drop(columns=[target_col])

        # 4. Initialize and Run FLAML
        automl = AutoML()
        
        automl_settings = {
            "time_budget": time_budget,
            "metric": 'auto',
            "estimator_list": estimator_list,
            "task": 'regression' if y.dtype in ['float64', 'int64'] else 'classification',
            "log_file_name": 'prism_training.log',
            "verbose": 0 
        }

        # Train the model!
        automl.fit(X_train=X, y_train=y, **automl_settings)

        print("\n✅ Training Complete!")
        print(f"🏆 Best Model Found: {automl.best_estimator}")
        print(f"📉 Best Loss: {automl.best_loss}")
        
        # ==========================================
        # 5. SECURE MODEL EXPORT (The Magic Step)
        # ==========================================
        if save_dir:
            model_path = os.path.join(save_dir, "trained_model.pkl")
            # Open the file in 'write binary' (wb) mode and dump the model
            with open(model_path, "wb") as f:
                pickle.dump(automl, f)
            print(f"💾 Model securely exported to: {model_path}")
        
        return automl