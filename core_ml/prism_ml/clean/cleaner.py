# This file cleans the csv files and returns dataframe
import polars as pl
from typing import Dict, Any
# Import our new custom exceptions
from prism_ml.exceptions import DataLoadError, CleaningConfigurationError

class PrismCleaner:
    def __init__(self):
        print("🔧 Prism Cleaner Initialized")

    def execute_cleaning(self, node_id: str, file_path: str, parameters: Dict[str, Any]) -> pl.DataFrame:
        """
        Executes the cleaning instructions generated by the AI Router.
        """
        print(f"📥 Loading dataset from: {file_path}")
        
        # 1. Industrial Error Handling for Missing Files
        try:
            df = pl.read_csv(file_path)
        except Exception as e:
            # We wrap the generic error in our custom domain error
            raise DataLoadError(file_path=file_path, message=str(e))

        # 2. Industrial Error Handling for Bad Configurations
        if not parameters:
            raise CleaningConfigurationError(node_id=node_id, message="Parameters dictionary cannot be empty.")

        # --- 1. Drop Requested Columns ---
        cols_to_drop = parameters.get("drop_columns", [])
        if cols_to_drop:
            valid_drops = [col for col in cols_to_drop if col in df.columns]
            
            # Optional strictness: If the LLM asked to drop a column that doesn't exist, we could raise an error here.
            # But for data cleaning, it's usually safer to just drop the ones we *do* find.
            if valid_drops:
                df = df.drop(valid_drops)
                print(f"🗑️ Dropped columns: {valid_drops}")

        # --- 2. Impute Missing Values ---
        impute_strategy = parameters.get("impute_strategy", "median")
        
        # Validate the strategy
        if impute_strategy not in ["median", "mean", "mode"]:
            raise CleaningConfigurationError(
                node_id=node_id, 
                message=f"Unknown impute_strategy '{impute_strategy}'. Must be median, mean, or mode."
            )
            
        print(f"🩹 Imputing missing values using strategy: {impute_strategy}")
        
        for col_name in df.columns:
            if df[col_name].null_count() > 0:
                dtype = df[col_name].dtype
                
                # Numeric Columns
                if dtype in [pl.Int64, pl.Int32, pl.Float64, pl.Float32]:
                    if impute_strategy == "median":
                        fill_value = df[col_name].median()
                    else:
                        fill_value = df[col_name].mean()
                    df = df.with_columns(pl.col(col_name).fill_null(fill_value))
                    
                # String/Categorical Columns
                elif dtype == pl.Utf8:
                    fill_value = df[col_name].mode()[0]
                    df = df.with_columns(pl.col(col_name).fill_null(fill_value))
                    
        print("✅ Data cleaning complete.")
        return df